using System.Collections.Generic;
using System.Linq;

using LMK.Editor.Registry;
using LMK.Runtime.GameplayTags;
using LMK.Runtime.Registry;

namespace LMK.Editor.GameplayTags
{
    /// <summary>
    /// Generates <c>GameplayTags.g.cs</c>: one <see cref="GameplayTag"/> constant per tag, in one nested class per
    /// registry. A constant holds the registry ID, the tag ID and the path, so it survives renames. The registry core's
    /// <see cref="RegistryCodeGen"/> writes it, in the tag kind's <see cref="STYLE"/>.
    /// </summary>
    /// <remarks>
    /// <b>Renames (policy C):</b> when a tag's constant name changes, the old name stays as an <c>[Obsolete]</c>
    /// alias of the new one, until <see cref="PruneAliases"/> finds no script using it. The previous generated file
    /// is the only record of old names, so it must be committed. Files written by 1.0.0 keep their aliases. <br/>
    /// <b>Deletes:</b> a deleted tag's constant and aliases disappear, so any use is a compile error. <br/>
    /// <b>Which:</b> every registry with code generation on (its Inspector toggle), as saved: staged tag edits are not
    /// included. <br/>
    /// <b>When:</b> saving tag edits writes it. Other changes only mark it as pending, and it's written when the
    /// editor loses focus, before Play Mode, before a build and on quit. It's only written if its content changed.
    /// </remarks>
    internal static class TagCodeGen
    {
        public const string DEFAULT_OUTPUT_PATH = TagRegistryService.ROOT_FOLDER + "/Generated/" + FILE_NAME;

        public const string ROOT_CLASS = "Tags";
        public const string MAIN_CLASS = RegistryCodeGen.MAIN_CLASS;
        public const string REGISTRY_FIELD = RegistryCodeGen.REGISTRY_FIELD;

        private const string FILE_NAME = "GameplayTags.g.cs";
        private const string GAMEPLAY_TAG = "global::LMK.Runtime.GameplayTags.GameplayTag";

        /// <summary>
        /// How the tag constants look: the layout of gameplay tags 1.0.0, so regenerating a 1.0.0 file changes nothing
        /// but the type of the IDs.
        /// </summary>
        public static readonly RegistryCodeStyle STYLE = new()
        {
            FileName = FILE_NAME,
            RootClass = ROOT_CLASS,
            MemberType = GAMEPLAY_TAG,
            Initializer = (_Field, _Id, _Name) => $"{GAMEPLAY_TAG}.FromId({_Field}, {_Id}, {_Name})",
            Header = new[]
            {
                "Generated by the Gameplay Tag Manager (com.lmk.gameplaytags) from the tag registries.",
                "Don't edit it: tag operations regenerate it. Commit it with the registries, because renamed",
                "tags keep their old names as [Obsolete] aliases only through this file.",
            },
            RootSummary = "Gameplay tag constants, one nested class per registry. A constant holds the tag's IDs, so it survives\n" +
                          "renames. Deleting a tag removes its constant.",
            RegistrySummaryNoun = "Tags",
            AliasComment = new[]
            {
                "Old names of renamed tags. Tools > GASU > Gameplay Tags > Prune Unused Code Aliases removes",
                "the ones no script uses.",
            },
            AssemblyReferences = new[] { "LMK.GameplayTags.Runtime", "LMK.Registry.Runtime" },
        };

        private static TagKind Kind => TagKind.Instance;

        /// <summary>
        /// Where the code is written. Only tests change it.
        /// </summary>
        internal static string OutputPath
        {
            get => Kind.CodeOutputPath;
            set => Kind.CodeOutputPath = value;
        }



        #region Pending
        /// <summary>
        /// Whether a tag operation changed the registries since the code was last written.
        /// </summary>
        public static bool IsPending => RegistryCodeGen.IsPending(Kind);

        /// <summary>
        /// Called after every registry write. The code is written by the next <see cref="Flush"/>.
        /// </summary>
        public static void MarkPending() => RegistryCodeGen.MarkPending(Kind);

        internal static void CancelPending() => RegistryCodeGen.CancelPending(Kind);

        /// <summary>
        /// Write the code if tag operations changed the registries since it was last written.
        /// </summary>
        public static void Flush() => RegistryCodeGen.Flush(Kind);
        #endregion



        #region Commands
        /// <summary>
        /// Generate the code from the loaded registries now. The file is only written if its content changed.
        /// </summary>
        public static RegistryResult Generate() => RegistryCodeGen.Generate(Kind);

        /// <summary>
        /// Remove the <c>[Obsolete]</c> aliases that no script in the project uses (policy C).
        /// </summary>
        /// <param name="_Pruned"> The removed aliases, as <c>Class.Name</c>. </param>
        public static RegistryResult PruneAliases(out IReadOnlyList<string> _Pruned) => RegistryCodeGen.PruneAliases(Kind, out _Pruned);

        /// <summary>
        /// The class a registry gets in the generated code, e.g. <c>Tags.Main</c>, or <see langword="null"/> if it
        /// isn't loaded. Computed as if every registry had code generation on.
        /// </summary>
        public static string ClassNameOf(RegistryGuid _RegistryId) => RegistryCodeGen.ClassNameOf(Kind, _RegistryId);
        #endregion



        #region Model
        /// <summary>
        /// A registry as code generation sees it.
        /// </summary>
        internal sealed class Registry
        {
            public RegistryGuid Id;
            public string Name;
            public bool IsMain;
            public readonly List<Tag> Tags = new();

            internal RegistryCodeGen.Registry ToCore()
            {
                var registry = new RegistryCodeGen.Registry { Id = Id, Name = Name, IsMain = IsMain };
                registry.Rows.AddRange(Tags.Select(e => new RegistryCodeGen.Row(e.Id, e.Path, e.Description)));
                return registry;
            }
        }

        internal readonly struct Tag
        {
            public readonly RegistryGuid Id;
            public readonly string Path;
            public readonly string Description;

            public Tag(RegistryGuid _Id, string _Path, string _Description = null)
            {
                Id = _Id;
                Path = _Path;
                Description = _Description;
            }
        }

        /// <summary>
        /// A constant or alias found in a generated file.
        /// </summary>
        internal readonly struct GeneratedMember
        {
            public readonly RegistryGuid RegistryId;
            public readonly string Name;
            public readonly RegistryGuid TagId;
            public readonly bool IsAlias;

            public GeneratedMember(RegistryGuid _RegistryId, string _Name, RegistryGuid _TagId, bool _IsAlias)
            {
                RegistryId = _RegistryId;
                Name = _Name;
                TagId = _TagId;
                IsAlias = _IsAlias;
            }
        }
        #endregion



        #region Source
        /// <summary>
        /// The source of the generated file.
        /// </summary>
        /// <param name="_PreviousSource"> The current generated file, read for the names of renamed tags. May be <see langword="null"/>. </param>
        /// <param name="_Namespace"> Namespace of the root class. Empty for the global namespace. </param>
        /// <param name="_Warnings"> Receives name clashes and dropped aliases. </param>
        /// <param name="_DropAliases"> Aliases (registry ID, name) to leave out: the prune step. </param>
        internal static string GenerateSource(IReadOnlyList<Registry> _Registries, string _PreviousSource, string _Namespace,
                                              ICollection<string> _Warnings = null, ISet<(RegistryGuid, string)> _DropAliases = null)
            => RegistryCodeGen.GenerateSource(STYLE, _Registries.Select(e => e.ToCore()).ToList(), _PreviousSource, _Namespace, _Warnings, _DropAliases);

        /// <summary>
        /// The constants and aliases of a generated file, with the registry each belongs to. Files written by 1.0.0 are
        /// read too.
        /// </summary>
        internal static List<GeneratedMember> ParseGenerated(string _Source)
            => RegistryCodeGen.ParseGenerated(_Source).Select(e => new GeneratedMember(e.RegistryId, e.Name, e.RowId, e.IsAlias)).ToList();

        /// <summary>
        /// Which of <paramref name="_Names"/> appear as whole words in the given scripts.
        /// </summary>
        internal static HashSet<string> FindUsedNames(IEnumerable<string> _Names, IEnumerable<string> _Files) => RegistryCodeGen.FindUsedNames(_Names, _Files);
        #endregion
    }
}
