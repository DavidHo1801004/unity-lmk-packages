using System.Collections.Generic;

using LMK.Editor.Registry;
using LMK.Runtime.AbilitySystem;
using LMK.Runtime.Registry;

namespace LMK.Editor.AbilitySystem
{
    /// <summary>
    /// Generates <c>GameplayAttributes.g.cs</c>: one <see cref="GameplayAttribute"/> constant per attribute, in one
    /// nested class per registry, e.g. <c>Attributes.Main.Vitals_Health</c>. A constant holds the registry ID, the
    /// attribute ID and the name, so it survives renames. The registry core's <see cref="RegistryCodeGen"/> writes it.
    /// </summary>
    /// <remarks>
    /// <b>Renames:</b> the old constant name stays as an <c>[Obsolete]</c> alias until Prune Unused Code Aliases finds
    /// no script using it. <b>Deletes:</b> the constant disappears, so any use is a compile error. <br/>
    /// <b>Assembly:</b> the code goes to <c>Assembly-CSharp</c> unless Project Settings > LMK > Registries names an
    /// assembly for gameplay attributes; then the core writes an assembly definition next to the code, referencing
    /// <c>LMK.AbilitySystem.Runtime</c>, so assembly-definition code can use the constants too.
    /// </remarks>
    internal static class AttributeCodeGen
    {
        private const string FILE_NAME = "GameplayAttributes.g.cs";
        private const string ROOT_CLASS = "Attributes";
        private const string GAMEPLAY_ATTRIBUTE = "global::LMK.Runtime.AbilitySystem.GameplayAttribute";

        public static readonly RegistryCodeStyle STYLE = new()
        {
            FileName = FILE_NAME,
            RootClass = ROOT_CLASS,
            MemberType = GAMEPLAY_ATTRIBUTE,
            Initializer = (_Field, _Id, _Name) => $"{GAMEPLAY_ATTRIBUTE}.FromId({_Field}, {_Id}, {_Name})",
            Header = new[]
            {
                "Generated by the Attribute Manager (com.lmk.abilitysystem) from the attribute registries.",
                "Don't edit it: attribute operations regenerate it. Commit it with the registries, because renamed",
                "attributes keep their old names as [Obsolete] aliases only through this file.",
            },
            RootSummary = "Gameplay attribute constants, one nested class per registry. A constant holds the attribute's IDs, so it\n" +
                          "survives renames. Deleting an attribute removes its constant.",
            RegistrySummaryNoun = "Attributes",
            AliasComment = new[]
            {
                "Old names of renamed attributes. Tools > LMK > Ability System > Prune Unused Attribute Code Aliases removes",
                "the ones no script uses.",
            },
            AssemblyReferences = new[] { "LMK.AbilitySystem.Runtime", "LMK.Registry.Runtime" },
        };

        private static AttributeKind Kind => AttributeKind.Instance;

        /// <summary>
        /// Where the code is written. Only tests change it.
        /// </summary>
        internal static string OutputPath
        {
            get => Kind.CodeOutputPath;
            set => Kind.CodeOutputPath = value;
        }

        /// <summary>
        /// Generate the code from the saved registries now. The file is only written if its content changed.
        /// </summary>
        public static RegistryResult Generate() => RegistryCodeGen.Generate(Kind);

        /// <summary>
        /// Remove the <c>[Obsolete]</c> aliases that no script in the project uses.
        /// </summary>
        public static RegistryResult PruneAliases(out IReadOnlyList<string> _Pruned) => RegistryCodeGen.PruneAliases(Kind, out _Pruned);

        /// <summary>
        /// The class a registry gets in the generated code, e.g. <c>Attributes.Main</c>.
        /// </summary>
        public static string ClassNameOf(RegistryGuid _RegistryId) => RegistryCodeGen.ClassNameOf(Kind, _RegistryId);
    }
}
