    /// <summary>
    /// The generator on its own, from hand-made registries, with a tag-shaped style.
    /// </summary>
    public sealed class CodeGenSourceTests
    {
        private static readonly RegistryGuid REGISTRY = RegistryGuid.Parse("6b1f0c2a9d7e4b3f8a5c1d0e2f3a4b5c");
        private static readonly RegistryGuid FIRE = RegistryGuid.Parse("3f2ae8d1b6c04a7f8c2d9e0b1a4f77c1");

        internal static RegistryCodeStyle TagStyle() => new()
        {
            FileName = "Tree.g.cs",
            RootClass = "Tags",
            MemberType = "global::Test.Tag",
            Initializer = (_Registry, _Id, _Name) => $"global::Test.Tag.FromId({_Registry}, {_Id}, {_Name})",
            Header = new[] { "Generated by the test." },
            RootSummary = "Test constants.",
            RegistrySummaryNoun = "Tags",
            AssemblyReferences = new[] { "LMK.Registry.Runtime" },
        };

        private static RegistryCodeGen.Registry Registry(params (RegistryGuid Id, string Name)[] _Rows)
            => Registry(REGISTRY, "Main", true, _Rows);

        private static RegistryCodeGen.Registry Registry(RegistryGuid _Id, string _Name, bool _IsMain, params (RegistryGuid Id, string Name)[] _Rows)
        {
            var registry = new RegistryCodeGen.Registry { Id = _Id, Name = _Name, IsMain = _IsMain };
            foreach (var (id, name) in _Rows)
                registry.Rows.Add(new RegistryCodeGen.Row(id, name));

            return registry;
        }

        private static string Generate(RegistryCodeGen.Registry _Registry, string _Previous = null, List<string> _Warnings = null, ISet<(RegistryGuid, string)> _Drop = null)
            => RegistryCodeGen.GenerateSource(TagStyle(), new[] { _Registry }, _Previous, string.Empty, _Warnings, _Drop);

        private static Dictionary<string, RegistryCodeGen.GeneratedMember> Members(string _Source)
            => RegistryCodeGen.ParseGenerated(_Source).ToDictionary(e => e.Name);



        [Test]
        public void Constant_HoldsRegistryIdRowIdAndName()
        {
            string source = Generate(Registry((FIRE, "Ability.Fire")));

            // The literals are the halves of the 32-digit text, read big-endian, as in the registry file.
            StringAssert.Contains("RegistryId = new global::LMK.Runtime.Registry.RegistryGuid(0x6b1f0c2a9d7e4b3fUL, 0x8a5c1d0e2f3a4b5cUL);", source);
            StringAssert.Contains(
                "Ability_Fire = global::Test.Tag.FromId(RegistryId, " +
                "new global::LMK.Runtime.Registry.RegistryGuid(0x3f2ae8d1b6c04a7fUL, 0x8c2d9e0b1a4f77c1UL), \"Ability.Fire\");", source);
            StringAssert.Contains("public static partial class Tags", source);
            StringAssert.Contains("public static partial class Main", source);
            StringAssert.StartsWith("// <auto-generated>\n//     Generated by the test.\n// </auto-generated>\n", source);

            var member = Members(source)["Ability_Fire"];
            Assert.AreEqual(REGISTRY, member.RegistryId);
            Assert.AreEqual(FIRE, member.RowId);
            Assert.IsFalse(member.IsAlias);
        }

        [Test]
        public void Rename_LeavesAnObsoleteAlias_UntilPruned()
        {
            string v1 = Generate(Registry((FIRE, "Ability.Fire")));
            string v2 = Generate(Registry((FIRE, "Ability.Burn")), v1);

            StringAssert.Contains("[global::System.Obsolete(\"Renamed to Tags.Main.Ability_Burn (\\\"Ability.Burn\\\").\")]", v2);
            StringAssert.Contains($"Ability_Fire = Ability_Burn; // alias of {FIRE}", v2);
            Assert.IsTrue(Members(v2)["Ability_Fire"].IsAlias);

            // A second rename: every old name points at the newest one.
            string v3 = Generate(Registry((FIRE, "Ability.Blaze")), v2);
            StringAssert.Contains("Ability_Fire = Ability_Blaze;", v3);
            StringAssert.Contains("Ability_Burn = Ability_Blaze;", v3);

            // Regenerating keeps the aliases.
            Assert.AreEqual(v3, Generate(Registry((FIRE, "Ability.Blaze")), v3));

            // Prune: unused aliases go, used ones stay, and never come back.
            string pruned = Generate(Registry((FIRE, "Ability.Blaze")), v3, _Drop: new HashSet<(RegistryGuid, string)> { (REGISTRY, "Ability_Fire") });
            Assert.IsFalse(Members(pruned).ContainsKey("Ability_Fire"));
            Assert.IsTrue(Members(pruned)["Ability_Burn"].IsAlias);
            Assert.AreEqual(pruned, Generate(Registry((FIRE, "Ability.Blaze")), pruned));
        }

        [Test]
        public void FilesOfGameplayTags10_KeepTheirAliases()
        {
            // As gameplay tags 1.0.0 wrote it: its own constant and GUID types.
            string v1 =
                "public static partial class Tags\n{\n    public static partial class Main\n    {\n" +
                "        public static readonly global::LMK.Runtime.GameplayTags.TagGuid RegistryId = new global::LMK.Runtime.GameplayTags.TagGuid(0x6b1f0c2a9d7e4b3fUL, 0x8a5c1d0e2f3a4b5cUL);\n" +
                "        public static readonly global::LMK.Runtime.GameplayTags.GameplayTag Ability_Burn = global::LMK.Runtime.GameplayTags.GameplayTag.FromId(RegistryId, new global::LMK.Runtime.GameplayTags.TagGuid(0x3f2ae8d1b6c04a7fUL, 0x8c2d9e0b1a4f77c1UL), \"Ability.Burn\");\n" +
                "        public static readonly global::LMK.Runtime.GameplayTags.GameplayTag Ability_Fire = Ability_Burn; // alias of 3f2ae8d1b6c04a7f8c2d9e0b1a4f77c1\n" +
                "    }\n}\n";

            var members = Members(v1);
            Assert.AreEqual(FIRE, members["Ability_Burn"].RowId);
            Assert.IsTrue(members["Ability_Fire"].IsAlias);

            string v2 = Generate(Registry((FIRE, "Ability.Blaze")), v1);
            StringAssert.Contains("Ability_Burn = Ability_Blaze;", v2);
            StringAssert.Contains("Ability_Fire = Ability_Blaze;", v2);
        }

        [Test]
        public void Prune_FindsUsesInScripts()
        {
            string folder = Path.Combine("Temp", "__RegistryCodeGenTests");
            Directory.CreateDirectory(folder);

            try
            {
                string script = Path.Combine(folder, "User.cs");
                File.WriteAllText(script, "class User { void M() { var t = Tags.Main.Ability_Burn; } } // Ability_Firestorm\n");

                var used = RegistryCodeGen.FindUsedNames(new[] { "Ability_Fire", "Ability_Burn" }, new[] { script });

                CollectionAssert.AreEquivalent(new[] { "Ability_Burn" }, used, "whole words only");
            }
            finally
            {
                Directory.Delete(folder, true);
            }
        }

        [Test]
        public void DeletedRow_LosesItsConstantAndAliases()
        {
            var other = RegistryGuid.Parse("9c41aa07e5d34b2c8f1e0d9a7b6c5d4e");
            string v1 = Generate(Registry((FIRE, "Ability.Fire"), (other, "Other")));
            string v2 = Generate(Registry((FIRE, "Ability.Burn"), (other, "Other")), v1);

            string v3 = Generate(Registry((other, "Other")), v2);

            CollectionAssert.AreEquivalent(new[] { "Other" }, Members(v3).Keys, "any use of the deleted row is now a compile error");
        }

        [Test]
        public void RenameThenAddTheOldName_TheNewRowTakesTheName()
        {
            var newFire = RegistryGuid.Parse("0a91c3e27f4b4d0c9e1f55b2c8d7a610");
            string v1 = Generate(Registry((FIRE, "Ability.Fire")));
            var warnings = new List<string>();

            string v2 = Generate(Registry((FIRE, "Ability.Burn"), (newFire, "Ability.Fire")), v1, warnings);

            var members = Members(v2);
            Assert.AreEqual(newFire, members["Ability_Fire"].RowId);
            Assert.IsFalse(members["Ability_Fire"].IsAlias);
            Assert.AreEqual(1, warnings.Count, string.Join("\n", warnings));
            StringAssert.Contains("Tags.Main.Ability_Burn", warnings[0]);
        }

        [Test]
        public void Names_ClashesKeywordsAndReservedNames()
        {
            var a = RegistryGuid.Parse("aaaaaaaa000000000000000000000001");
            var b = RegistryGuid.Parse("bbbbbbbb000000000000000000000002");
            var warnings = new List<string>();

            string source = Generate(Registry(
                (a, "A.B_C"),
                (b, "A_B.C"),
                (RegistryGuid.Parse("c0000000000000000000000000000003"), "class"),
                (RegistryGuid.Parse("d0000000000000000000000000000004"), "1st"),
                (RegistryGuid.Parse("e0000000000000000000000000000005"), "RegistryId"),
                (RegistryGuid.Parse("f0000000000000000000000000000006"), "Main")), null, warnings);

            var members = Members(source);
            Assert.AreEqual(a, members["A_B_C_aaaaaaaa"].RowId, "a clash never gives the name to one row silently");
            Assert.AreEqual(b, members["A_B_C_bbbbbbbb"].RowId);
            Assert.IsFalse(members.ContainsKey("A_B_C"));
            StringAssert.Contains(" @class = ", source);
            Assert.IsTrue(members.ContainsKey("_1st"));
            Assert.IsTrue(members.ContainsKey("RegistryId_e0000000"));
            Assert.IsTrue(members.ContainsKey("Main_f0000000"), "a member can't share its class's name");
            Assert.AreEqual(4, warnings.Count, string.Join("\n", warnings));
        }

        [Test]
        public void OneClassPerRegistry_MainKeepsItsName()
        {
            var package = RegistryGuid.Parse("a0000000000000000000000000000001");
            var registries = new[]
            {
                Registry(REGISTRY, "Main", true, (FIRE, "Fire")),
                Registry(package, "Main", false, (RegistryGuid.Parse("b0000000000000000000000000000002"), "Ice")),
            };

            string source = RegistryCodeGen.GenerateSource(TagStyle(), registries, null, "My.Game");

            StringAssert.Contains("namespace My.Game", source);
            StringAssert.Contains("public static partial class Main\n", source);
            StringAssert.Contains("public static partial class Main_a0000000", source);
        }

        [Test]
        public void Output_IsDeterministicWithLfLineEndings()
        {
            var registry = Registry((FIRE, "Ability.Fire"), (RegistryGuid.Parse("9c41aa07e5d34b2c8f1e0d9a7b6c5d4e"), "Ability.Ice"));
            var reversed = Registry((RegistryGuid.Parse("9c41aa07e5d34b2c8f1e0d9a7b6c5d4e"), "Ability.Ice"), (FIRE, "Ability.Fire"));

            string source = Generate(registry);

            StringAssert.DoesNotContain("\r", source);
            Assert.AreEqual(source, Generate(reversed));
        }
    }



    /// <summary>
    /// Code generation of a kind: when files are written, and what settings change.
    /// </summary>
    public sealed class CodeGenTests : KindTestBase
    {
        private const string CODE_FOLDER = "Temp/RegistryCoreTests/Code";

        [SetUp]
        public void EnableCode()
        {
            a.code = CodeGenSourceTests.TagStyle();
            a.CodeOutputPath = $"{CODE_FOLDER}/Tree.g.cs";
        }

        [TearDown]
        public void ResetCodeSettings()
        {
            var settings = RegistrySettings.instance;
            settings.SetCodeNamespace(a, null, false);
            settings.SetCodeAssembly(a, null, false);
            settings.SetCodeGenerated(a, a.MainRegistryId, true, false);
            RegistryCodeGen.CancelPending(a);
        }

        private static RegistryResult Add<TAsset>(TreeKindBase<TAsset> _Kind, string _Segment, string _Description = "") where TAsset : RegistryAsset<TreeRow>
            => RegistryEdit.Apply(_Kind, "Add", data =>
            {
                var id = RegistryGuid.NewGuid();
                data.rows.Add(new RegistryRow<TreeRow>(id, new TreeRow(RegistryGuid.Zero, _Segment, false, _Description)));
                return RegistryResult.Ok(id);
            });

        private string Code => File.Exists(a.CodeOutputPath) ? File.ReadAllText(a.CodeOutputPath) : null;

        [Test]
        public void StagedEditsAreNotGenerated_SaveWritesTheCode()
        {
            Add(a, "Fire", "Burns");
            Assert.IsTrue(Code == null || !Code.Contains("Fire"), "staged edits are not generated");

            Assert.IsTrue(RegistrySession.Save().Success);

            StringAssert.Contains(" Fire = global::Test.Tag.FromId(RegistryId", Code);
            StringAssert.Contains("<c>Fire</c>: Burns", Code);
            Assert.IsFalse(RegistryCodeGen.IsPending(a));
        }

        [Test]
        public void TheLockCoversTheCode_AndUnchangedCodeIsNotWritten()
        {
            Add(a, "Fire");
            var provider = new RecordingLockProvider();
            RegistryLockProvider.Current = provider;

            RegistrySession.Save();

            CollectionAssert.Contains(provider.requests[0], a.CodeOutputPath, "a save locks the code it writes");
            var written = File.GetLastWriteTimeUtc(a.CodeOutputPath);
            provider.requests.Clear();

            Assert.IsTrue(RegistryCodeGen.Generate(a).Success);
            Assert.AreEqual(written, File.GetLastWriteTimeUtc(a.CodeOutputPath));
            Assert.IsEmpty(provider.requests, "nothing to write: no lock needed");
        }

        [Test]
        public void WithoutTheLock_CodeStaysPending()
        {
            Add(a, "Fire");
            RegistrySession.Save();
            RegistryCodeGen.MarkPending(a);
            File.Delete(a.CodeOutputPath);
            RegistryLockProvider.Current = new RecordingLockProvider { refuse = true };

            UnityEngine.TestTools.LogAssert.Expect(UnityEngine.LogType.Warning, new System.Text.RegularExpressions.Regex("not generated"));
            RegistryCodeGen.Flush(a);

            Assert.IsTrue(RegistryCodeGen.IsPending(a));
            Assert.IsFalse(File.Exists(a.CodeOutputPath));

            RegistryLockProvider.Current = null;
            RegistryCodeGen.FlushAll();
            Assert.IsTrue(File.Exists(a.CodeOutputPath));
        }

        [Test]
        public void Settings_RegistryToggleNamespaceAndAssembly()
        {
            Add(a, "Fire");
            RegistrySession.Save();
            var settings = RegistrySettings.instance;

            settings.SetCodeNamespace(a, "My.Game", false);
            settings.SetCodeAssembly(a, "Game.Constants", false);
            RegistryCodeGen.Generate(a);

            StringAssert.Contains("namespace My.Game", Code);
            string asmdef = $"{CODE_FOLDER}/Game.Constants.asmdef";
            Assert.IsTrue(File.Exists(asmdef));
            StringAssert.Contains("\"name\": \"Game.Constants\"", File.ReadAllText(asmdef));
            StringAssert.Contains("\"LMK.Registry.Runtime\"", File.ReadAllText(asmdef));
            CollectionAssert.Contains(a.GeneratedFiles, asmdef);

            settings.SetCodeGenerated(a, a.MainRegistryId, false, false);
            RegistryCodeGen.Generate(a);
            Assert.IsFalse(Code != null && Code.Contains("class Main"), "a registry with code generation off gets no class");
        }

        [Test]
        public void KindsWithoutAStyle_GenerateNothing()
        {
            Add(b, "Fire");
            RegistrySession.Save();

            CollectionAssert.IsEmpty(b.GeneratedFiles);
            Assert.IsNull(b.CodeOutputPath);
            Assert.IsTrue(RegistryCodeGen.Generate(b).Success);
        }

        [Test]
        public void ClassNameOf_NamesTheRegistrysClass()
        {
            Assert.AreEqual("Tags.Main", RegistryCodeGen.ClassNameOf(a, a.MainRegistryId));
            Assert.IsNull(RegistryCodeGen.ClassNameOf(a, RegistryGuid.NewGuid()));
        }
    }
